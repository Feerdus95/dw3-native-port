"""Markdown tables of the partners' forms and techniques, from docs/data/tables.json (see tools/dump_tables.py, version 2+).

Usage:  python tools/forms_report.py [tables.json] [out.md]
        tables.json defaults to <workspace>/docs/data/tables.json, out.md to <workspace>/docs/data/forms_techs.md
Report version: 1

Only what the tables say, no behaviour is inferred: it lists the techniques each Digimon (DigimonData.skills / skillLevels /
knownLevels) AVAILABLE to learn, not the ones the player or the AI end up using. Names are not resolved (the name text file
uses its own glyph table): rows are identified by DIGIMON_DATA index, Digimon id and nameId.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "docs", "data", "tables.json")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "docs", "data", "forms_techs.md")

BATTLE_STATS = ["STR", "DEF", "SPI", "WIS", "SPD", "CHR"]
KIND = {2: "fis", 3: "mag"}  # TechData.icon (TECH_PHYSICAL, TECH_MAGIC); other values are not offensive techniques
BLAST_TIERS = ["<4", "4-18", "19-38", "39-69", ">=70"]  # WFIGHTMN_blast, by the partner's level


def need_text(stat, value):
    if stat == 0:
        return ""
    if stat <= 6:
        return "%s>=%d" % (BATTLE_STATS[stat - 1], value)
    if stat == 7:
        return "nivel>=%d" % value
    return "resist%d>=%d" % (stat - 8, value)


def main():
    with open(SRC, encoding="utf-8") as f:
        t = json.load(f)
    D, E, T = t["digimon"], t["evolutions"], {x["id"]: x for x in t["techs"]}
    out = ["<!-- generated by native/tools/forms_report.py v1 from tables.json; do not edit by hand -->", ""]

    used = sorted({s for d in D for s in d["skills"] + [d["pairTech"]] if s})
    out += ["## A. Técnicas referenciadas por DIGIMON_DATA (skills[0..6], pairTech)", "",
            "`tipo`: fis = icon 2 (física), mag = icon 3 (mágica), otro = icon n (no ofensiva). `elem` solo si element>=2; `fam` solo si family>=2.",
            "`efecto` = TECH_EFFECT_* (`-` si <2: ninguno; 9 = golpe múltiple, 8 = drenaje HP, ...); `prob/poder` = effectChance/effectPower (solo con efecto);",
            "`script` y `hits` son los de TechData.", "",
            "| id | tipo | MP | poder | prec | elem | elemPow | fam | efecto | prob/poder | script | hits |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i in used:
        x = T[i]
        fx = x["effect"] >= 2
        out.append("| %d | %s | %d | %d | %d | %s | %d | %d | %s | %s | %d | %d |" % (
            i, KIND.get(x["icon"], "icon%d" % x["icon"]), x["mp"], x["power"], x["accuracy"],
            x["element"] if x["element"] >= 2 else "-", x["elementPower"], x["family"] if x["family"] >= 2 else 0,
            x["effect"] if fx else "-", "%d/%d" % (x["effectChance"], x["effectPower"]) if fx else "-", x["script"], x["hitCount"]))

    out += ["", "## B. Compañeros (DIGIMON_DATA[0..7])", "",
            "| idx | id | nameId | ataque básico skills[0] | firma skills[6] | blastForms (índice+1) por tramo de nivel del compañero | fam |",
            "|---|---|---|---|---|---|---|"]
    for d in D[:8]:
        out.append("| %d | %d | %d | %d | %d | %s | %d |" % (
            d["index"], d["id"], d["nameId"], d["skills"][0], d["skills"][6],
            ", ".join("%s:%d" % (BLAST_TIERS[k], d["blastForms"][k]) for k in range(5)), d["family"]))

    out += ["", "## C. Formas aprendibles (DIGIMON_DATA[8..51]; `evo` = índice+1 que usan las listas de evolución)", "",
            "`skills[1..6]@nivel` = técnica@`skillLevels` (nivel de la forma, no del compañero); `known` = `knownLevels[0..4]`.",
            "Stats = `battleStats[0..4]` (STR DEF SPI WIS SPD): lo que la forma SUMA al compañero en combate.", "",
            "| evo | idx | id | nameId | fam | stats | resist0-6 | expLevel | básico | skills[1..6]@nivel | known | pair (tech/partner) |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for d in D[8:52]:
        sk = ", ".join("%d@%d" % (s, lv) if s else "-" for s, lv in zip(d["skills"][1:], d["skillLevels"]))
        out.append("| %d | %d | %d | %d | %d | %s | %s | %d | %d | %s | %s | %d/%d |" % (
            d["index"] + 1, d["index"], d["id"], d["nameId"], d["family"], " ".join(str(v) for v in d["battleStats"][:5]),
            " ".join(str(v) for v in d["resistances"]), d["expLevel"], d["skills"][0], sk,
            " ".join(str(v) for v in d["knownLevels"]), d["pairTech"], d["pairPartner"]))
    extra = D[52:]
    out += ["", "Entradas DIGIMON_DATA[52..%d] (fuera de las listas de evolución): %s" % (
        len(D) - 1, "; ".join("idx %d id %d nameId %d básico %d" % (d["index"], d["id"], d["nameId"], d["skills"][0]) for d in extra))]

    out += ["", "## D. Requisitos de cada forma por compañero (STFGTREP_evolutionLists)", "",
            "`needs`: forma(evo)@nivel mínimo de ESA forma; `stat`: condición sobre el compañero. Aprendida al terminar un combate si cumple todo",
            "(`STFGTREP_learnDigimon`: la primera de la lista aún no tenida que cumpla; se repite hasta que no quede ninguna).", ""]
    for p in range(8):
        out += ["### Compañero %d (id %d)" % (p, D[p]["id"]), "", "| evo | needs | stat | prof |", "|---|---|---|---|"]
        by = {e["digimon"]: e for e in E[p]}
        depth = {}

        def dep(k, seen=()):
            if k in depth:
                return depth[k]
            if k in seen:
                return -1  # cycle
            ds = [dep(n[0], seen + (k,)) for n in by[k]["needs"] if n[0]]
            depth[k] = 1 + max(ds) if ds else 0
            return depth[k]

        for e in E[p]:
            nd = ", ".join("%d@%d" % (a, b) for a, b in e["needs"] if a) or "-"
            out.append("| %d | %s | %s | %d |" % (e["digimon"], nd, need_text(e["stat"], e["value"]) or "-", dep(e["digimon"])))
        out.append("")

    os.makedirs(os.path.dirname(os.path.abspath(OUT)), exist_ok=True)
    tmp = OUT + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    os.replace(tmp, OUT)
    print("techs", len(used), "forms 44 ->", OUT)


main()
