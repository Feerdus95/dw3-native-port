"""Bakes Pixel Digivolve at its crisp size into launcher/font_data.inc.

Only the bitmap goes in the repo: the font's licence allows embedding in software
but not offering the font itself for download. Get the .otf from pixelsagas.com or
dafont.com and run: python tools/bake_launcher_font.py "Pixel Digivolve.otf"
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

SIZE = 10
CELL_W = 16
CELL_H = 18
BASELINE = 13
CHARS = [*range(32, 127), *range(161, 256), 0x152, 0x153]
OUT = Path(__file__).resolve().parents[1] / "launcher/font_data.inc"
# At this size the font's M, N and W come out mangled (W reads as H): redrawn by hand, accents kept.
FIXED = {
    "M": ["##...##", "###.###", "#######", "##.#.##", "##...##", "##...##", "##...##"],
    "N": ["##..##", "###.##", "###.##", "######", "##.###", "##.###", "##..##"],
    "W": ["##...##", "##...##", "##...##", "##.#.##", "#######", "###.###", "##...##"],
}
FIXED.update({"m": FIXED["M"], "n": FIXED["N"], "w": FIXED["W"], "Ñ": FIXED["N"], "ñ": FIXED["N"]})


def main():
    font = ImageFont.truetype(sys.argv[1], SIZE)
    glyphs = []
    for cp in CHARS:
        im = Image.new("1", (CELL_W, CELL_H), 0)
        draw = ImageDraw.Draw(im)
        draw.fontmode = "1"
        draw.text((0, BASELINE), chr(cp), font=font, fill=1, anchor="ls")
        rows = [sum(1 << x for x in range(CELL_W) if im.getpixel((x, y))) for y in range(CELL_H)]
        for i, row in enumerate(FIXED.get(chr(cp), [])):
            rows[BASELINE - 7 + i] = sum(1 << x for x, c in enumerate(row) if c == "#")
        glyphs.append((cp, round(font.getlength(chr(cp))), rows))
    top = min(y for _, _, rows in glyphs for y in range(CELL_H) if rows[y])
    bottom = max(y for _, _, rows in glyphs for y in range(CELL_H) if rows[y])
    lines = [
        "/* Generated by tools/bake_launcher_font.py from Pixel Digivolve (Pixel Sagas, Neale Davidson). */",
        f"#define FONT_H {bottom - top + 1}",
        f"#define FONT_CAP_TOP {BASELINE - round(font.getbbox('H', anchor='ls')[3] - font.getbbox('H', anchor='ls')[1]) - top}",
        "static const struct { Uint16 cp; Uint8 advance; Uint16 rows[FONT_H]; } FONT[] = {",
    ]
    for cp, advance, rows in glyphs:
        lines.append(f"    {{{cp}, {advance}, {{{', '.join(str(r) for r in rows[top:bottom + 1])}}}}},")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print(f"{OUT}: {len(glyphs)} glyphs, {bottom - top + 1} rows, widest {max(a for _, a, _ in glyphs)}")


if __name__ == "__main__":
    main()
