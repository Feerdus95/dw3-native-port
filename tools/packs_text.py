"""The extra starter packs' texts (tools/packs_text/<language>.toml) in the
game's text encoding, into platform/packs_text.h: one text file each, as the
game's (a count, each string's offset, the strings). Encoded by ddw3's
mklang-file (https://github.com/markisha64/ddw3), passed as its path:

    python native/tools/packs_text.py path/to/mklang-file.exe

Index: 0 "", 1-3 the packs' names, 4-6 the labels D E F, 7-9 the packs'
texts, 10 Veemon's text, 11 Veemon's greeting in the lobby, 12-13 the word
of the intro's text and the one that replaces it ("three", "six").
And the port's other texts: 14 fast travel's question.
"""
import subprocess
import sys
import tempfile
from pathlib import Path

NATIVE = Path(__file__).resolve().parents[1]
LANGUAGES = ["eng", "fra", "ita", "ger", "spn"]


def main():
    out = ["/* Generated by tools/packs_text.py from tools/packs_text/<language>.toml: do not edit */", ""]
    with tempfile.TemporaryDirectory() as tmp:
        for lang in LANGUAGES:
            src, dst = NATIVE / "tools/packs_text" / f"{lang}.toml", Path(tmp) / f"{lang}.bin"
            subprocess.run([sys.argv[1], str(src), "--output", str(dst)], check=True)
            b = dst.read_bytes()
            b += bytes(-len(b) % 4)
            words = [int.from_bytes(b[i:i + 4], "little") for i in range(0, len(b), 4)]
            out.append(f"static const uint32_t PACKS_TEXT_{lang.upper()}[] = {{")
            out += ["    " + ", ".join(f"0x{w:08X}" for w in words[i:i + 6]) + "," for i in range(0, len(words), 6)]
            out += ["};", ""]
    (NATIVE / "platform/packs_text.h").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("platform/packs_text.h")


if __name__ == "__main__":
    main()
